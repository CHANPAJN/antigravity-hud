        public static float GetSystemDpiScale()
        {
            IntPtr hdc = GetDC(IntPtr.Zero);
            if (hdc == IntPtr.Zero) return 1.0f;
            try
            {
                int dpiX = GetDeviceCaps(hdc, 88);
                return dpiX > 0 ? (dpiX / 96.0f) : 1.0f;
            }
            finally
            {
                ReleaseDC(IntPtr.Zero, hdc);
            }
        }
